import sys
from pathlib import Path

import numpy as np
import pandas as pd
import statsmodels.api as sm
from scipy import stats

sys.path.insert(0, str(Path(__file__).resolve().parent))
from paths import PROCESSED_DIR

SEP = "=" * 88
MAP = {
    "ברצלונה": "BAR", "צסקא מוסקבה": "CSK", "ריאל מדריד": "MAD",
    "חימקי": "KHI", "מילאנו": "MIL", "פנרבחצה": "ULK", "זניט": "DYR",
    "אנדולו אפס": "IST", 'מכבי ת"א': "TEL", "באיירן": "MUN",
    "באסקוניה": "BAS", "אולימפיאקוס": "OLY", "ולנסיה": "PAM",
    "פנאתינייקוס": "PAN", "ז'לגיריס": "ZAL", "ASVEL": "ASV",
    "אלבה ברלין": "BER", "הכוכב האדום": "RED", "מונקו": "MCO",
    "פרטיזן": "PAR", "וירטוס": "VIR", "פריז": "PRS",
    'הפועל ת"א': "HTA", "דובאי": "DUB",
}


def h(t):
    print("\n" + SEP + f"\n{t}\n" + SEP)


def main():
    print(SEP)
    print("depth_vs_budget — האם הכוכב בקבוצה עשירה משחק פחות")
    print("תחזיות ננעלו. ראו ראש הקובץ.")
    print(SEP)

    ps = pd.read_csv(PROCESSED_DIR / "player_season.csv",
                     dtype={"player_code": str})
    b = pd.read_csv(PROCESSED_DIR / "club_budgets_gemini.csv")
    b["team"] = b.club.map(MAP)
    b = b[b.team.notna() & b.gross_eur.notna()]

    p = ps[ps.min_per_game > 0].copy()
    p["mt"] = p.min_per_game * p.games
    rows = []
    for (s, t), g in p.groupby(["season", "team"]):
        if len(g) < 8:
            continue
        v = np.sort(g.min_per_game.values)[::-1]
        sh = g.mt / g.mt.sum()
        rows.append(dict(
            season=s, team=t, n=len(g),
            top1=v[0], top2=float(v[:2].mean()),
            top2_share=float(np.sort(sh.values)[::-1][:2].sum()),
            n15=int((g.min_per_game >= 15).sum()),
            n20=int((g.min_per_game >= 20).sum()),
            hhi=float((sh ** 2).sum())))
    d = pd.DataFrame(rows).merge(b[["season", "team", "gross_eur"]],
                                 on=["season", "team"], how="inner")
    d["lgb"] = np.log(d.gross_eur)
    print(f"\n  n = {len(d)} עונות-מועדון עם תקציב   "
          f"(עונות: {sorted(d.season.unique())})")

    # נרמול בתוך עונה — 30 / 34 / 38 מחזורים.
    def z(x):
        return (x - x.mean()) / x.std(ddof=1)
    cols = ["top1", "top2", "top2_share", "n15", "n20", "hhi", "lgb"]
    for c in cols:
        d[c + "_z"] = d.groupby("season")[c].transform(z)

    h("התוצאה — כל מדד מול log(תקציב), מנורמל בתוך עונה")
    print(f"  {'מדד':<28}{'r':>9}{'p':>9}{'הכיוון שנחזה':>16}")
    tests = [
        ("דקות השחקן המוביל", "top1", "שלילי"),
        ("דקות שני המובילים", "top2", "שלילי"),
        ("נתח הדקות של השניים", "top2_share", "שלילי"),
        ("שחקנים מעל 15 דק'", "n15", "חיובי"),
        ("שחקנים מעל 20 דק'", "n20", "חיובי"),
        ("ריכוזיות הדקות (HHI)", "hhi", "שלילי"),
    ]
    res = {}
    for lab, c, exp in tests:
        r, pv = stats.pearsonr(d.lgb_z, d[c + "_z"])
        res[c] = (r, pv)
        ok = "✅" if ((r < 0) == (exp == "שלילי")) and pv < 0.05 else \
             ("~" if (r < 0) == (exp == "שלילי") else "❌")
        print(f"  {lab:<28}{r:>+9.3f}{pv:>9.3f}{exp:>12}  {ok}")

    h("במספרים גולמיים — שליש עליון מול שליש תחתון של התקציב")
    d["tier"] = d.groupby("season").lgb.transform(
        lambda x: pd.qcut(x, 3, labels=["ענייה", "בינונית", "עשירה"]))
    g = d.groupby("tier", observed=True).agg(
        n=("top1", "size"), תקציב=("gross_eur", "mean"),
        מוביל=("top1", "mean"), שניים=("top2", "mean"),
        נתח_שניים=("top2_share", "mean"),
        מעל15=("n15", "mean"), מעל20=("n20", "mean"))
    print(g.round(2).to_string())

    lo = d[d.tier == "ענייה"]
    hi = d[d.tier == "עשירה"]
    t1, p1 = stats.ttest_ind(lo.top1, hi.top1, equal_var=False)
    t2, p2 = stats.ttest_ind(lo.n15, hi.n15, equal_var=False)
    print(f"\n  הפרש דקות המוביל (ענייה − עשירה): "
          f"{lo.top1.mean()-hi.top1.mean():+.2f} דק'  "
          f"(t={t1:+.2f}, p={p1:.3f})")
    print(f"  הפרש מס' שחקנים מעל 15 דק' (עשירה − ענייה): "
          f"{hi.n15.mean()-lo.n15.mean():+.2f}  (t={-t2:+.2f}, p={p2:.3f})")

    h("איזה ערוץ חזק יותר")
    m = sm.OLS(d.lgb_z, sm.add_constant(
        d[["top1_z", "n15_z"]].astype(float))).fit()
    print(f"  שני המדדים יחד מסבירים {m.rsquared:.1%} מהשונות בתקציב")
    for c, lab in [("top1_z", "דקות המוביל"), ("n15_z", "עומק")]:
        print(f"    {lab:<14} β={m.params[c]:+.3f}  t={m.tvalues[c]:+.2f}  "
              f"p={m.pvalues[c]:.3f}")

    h("מול התחזיות")
    for nm, dd in [("אלמוג", PRED_ALMOG), ("קלוד", PRED_CLAUDE)]:
        print(f"  {nm}:")
        for k, v in dd.items():
            print(f"    {k:<12} {v}")
    print(SEP)


if __name__ == "__main__":
    main()