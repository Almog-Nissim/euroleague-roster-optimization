"""
league_jump_test.py  (Day 6)
----------------------------
האם אפשר לתמחר שחקן ליגה מקומית לפי מה שיעשה ביורוליג?

--------------------------------------------------------------------
למה זה מבחן אחר מ-league_conversion_test
--------------------------------------------------------------------
המקדם 0.729 נאמד על שחקנים ש**שיחקו בשתי המסגרות באותה עונה** -
כלומר שחקני מכבי והפועל. אבל אלה כבר שחקני יורוליג. הם לא
"קפצו" - הם רק שיחקו גם בבית.

השאלה המעשית היא אחרת: שחקן שהיה **רק** בליגה המקומית בעונה t-1,
ועבר ליורוליג ב-t. עליו רוצים להחיל את המקדם, ועליו הוא לא כויל.

זו הטיית בחירה קלאסית, ויש לה כיוון צפוי: מי שכבר משחק יורוליג
הוא ברמת יורוליג. מי שנבחר לעלות - לא בהכרח.

--------------------------------------------------------------------
המבחן
--------------------------------------------------------------------
12 שחקנים שעשו את הקפיצה בפועל, 2024-2025. לכל אחד יש גם קלט
(ppm בליגה המקומית ב-t-1) וגם תוצאה (ppm ביורוליג ב-t).

מחילים עליהם את המקדם 0.729 ובודקים את השגיאה.

**אין כאן מודל ואין אמידה** - רק החלה של מקדם שנאמד במקום אחר
על נתונים שכבר ידועים.

הרצה:
    python src/audits/league_jump_test.py
"""

import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from paths import PROCESSED_DIR

# המקדם כפי שנאמד ב-league_conversion_test על 40 זוגות שתי-מסגרות
COEF = 0.729
COEF_SD = 0.247

# 12 קפיצות שאומתו ידנית. שתי התאמות אוטומטיות נזרקו:
#   GABRIEL, WENYEN <-> גור לביא   (0.83, שגוי)
#   LEE, SABEN      <-> גיל בני    (0.75, שגוי)
# שתיהן זיהוי-יתר של המצליב הגלובלי - ראו ההערה ב-
# match_israeli_league על כך שהשיטה עובדת רק תחת אילוץ סגל.
JUMPS = [
    ("HOARD, JAYLEN", 2024, 0.887, 0.573),
    ("RANDOLPH, LEVI", 2024, 0.525, 0.438),
    ("BLAKENEY, ANTONIO", 2025, 0.545, 0.474),
    ("MOTLEY, JOHNATHAN", 2025, 0.804, 0.574),
    ("WAINRIGHT, ISH", 2025, 0.436, 0.198),
    ("CABOCLO, BRUNO", 2025, 0.726, 0.550),
    ("LAVI, GUR", 2025, 0.623, 0.296),
    ("GINAT, TOMER", 2025, 0.716, 0.313),
    ("EDWARDS, KESSLER", 2025, 0.637, 0.380),
    ("TIMOR, BAR", 2025, 0.387, 0.321),
    ("PALATIN, GUY", 2025, 0.338, 0.094),
    ("SEGEV, ITAY", 2025, 0.553, -0.670),
]
SEP = "=" * 74


def main():
    d = pd.DataFrame(JUMPS, columns=["player", "season", "il_ppm", "el_ppm"])
    d["ratio"] = d.el_ppm / d.il_ppm
    d["pred"] = d.il_ppm * COEF
    d["err"] = d.pred - d.el_ppm

    print(SEP)
    print("מבחן הקפיצה — הליגה המקומית כמנבא ליורוליג")
    print(f"המקדם {COEF} מוחל על מי שבאמת קפץ. n={len(d)}")
    print(SEP)

    print(f"\n{'שחקן':<22}{'עונה':>6}{'ppm מקומי':>11}{'חזוי':>8}"
          f"{'בפועל':>9}{'שגיאה':>9}{'יחס':>8}")
    for t in d.sort_values("ratio").itertuples():
        print(f"{t.player[:21]:<22}{t.season:>6}{t.il_ppm:>11.3f}"
              f"{t.pred:>8.3f}{t.el_ppm:>9.3f}{t.err:>+9.3f}{t.ratio:>8.2f}")

    print("\n" + SEP)
    print("היחס: קופצים מול מי שכבר היה שם")
    print(SEP)
    print(f"  קופצים        : חציון {d.ratio.median():.3f} | "
          f"ממוצע {d.ratio.mean():.3f} | סטיית תקן {d.ratio.std():.3f}")
    print(f"  שתי-מסגרות    : חציון {COEF:.3f} | "
          f"סטיית תקן {COEF_SD:.3f}   <- עליו כויל")
    print(f"\n  סטיית התקן של הקופצים גדולה פי "
          f"{d.ratio.std() / COEF_SD:.1f}.")

    print("\n" + SEP)
    print("השגיאה")
    print(SEP)
    mae = float(d.err.abs().mean())
    naive = float((d.el_ppm - d.el_ppm.median()).abs().mean())
    print(f"  MAE של המקדם        : {mae:.4f}")
    print(f"  MAE של ניחוש חציון  : {naive:.4f}")
    print(f"  שיפור               : {1 - mae / naive:+.1%}")
    print(f"\n  הטיה ממוצעת         : {d.err.mean():+.4f}  "
          f"({d.err.mean() / d.el_ppm.mean():+.0%} מהתפוקה הממוצעת)")
    print(f"  מעריך ביתר          : {int((d.err > 0).sum())}/{len(d)}")

    print("\n" + SEP)
    print("הכרעה")
    print(SEP)
    bias = d.err.mean()
    if bias > 0.05 and (d.err > 0).mean() >= 0.6:
        print("  🔴 **המקדם מעריך ביתר את הקופצים באופן שיטתי.**")
        print("  הוא כויל על שחקנים שכבר היו ברמת יורוליג, ומוחל על")
        print("  מי שרק נבחר לעלות. זו הטיית בחירה, לא רעש.")
        print("\n  להוסיף מועמדי ליגה מקומית למאגר עם המקדם הזה פירושו")
        print("  להזרים לאופטימייזר קבוצה שמוערכת ביתר בשיטתיות -")
        print("  והוא בוחר בדיוק את מי שמוערך ביתר. קללת המנצח")
        print("  שנמדדה ב--10.9% תחריף.")
    else:
        print("  המקדם אינו מוטה על הקופצים.")

    g = d[d.player == "LAVI, GUR"].iloc[0]
    print(f"\n  --- המקרה שבגללו התחלנו ---")
    print(f"  גור לביא: {g.il_ppm:.3f} מקומי -> חזוי {g.pred:.3f} -> "
          f"בפועל {g.el_ppm:.3f}")
    print(f"  הערכת יתר של {g.pred / g.el_ppm - 1:.0%}. והוא לא חריג -")
    print(f"  הוא במרכז ההתפלגות של הקופצים.")

    print("\n" + SEP)
    print("סייגים")
    print(SEP)
    print("  - n=12. זה מדגם קטן, וסטיית התקן שלו נשלטת ע\"י שגב")
    print("    (ppm שלילי ביורוליג). בלעדיו התמונה מתונה יותר,")
    print("    אבל ההטיה בכיוון נשארת: 7 מתוך 11 מוערכים ביתר.")
    print("  - הקופצים אינם מדגם אקראי - הם מי שמועדון בחר להעלות,")
    print("    כלומר כבר סוננו כלפי מעלה. זה מטה את ההטיה **כלפי")
    print("    מטה**, כלומר האמת גרועה יותר.")
    print(SEP)


if __name__ == "__main__":
    main()