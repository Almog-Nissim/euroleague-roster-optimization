"""
sensitivity_concentration.py  (Day 8)
-------------------------------------
**מחקר הרגישות** — השאלה שהפרויקט הגדיר ביום 3 ולא נגע בה עד היום.

--------------------------------------------------------------------
השאלה
--------------------------------------------------------------------
> בהינתן מבנה עלות, איך ההקצאה על פני סגל מגיבה, וכמה היא רגישה
> למבנה.

**לא** "מה הסגל האופטימלי". הפלט הוא **עקומת תגובה**, ולכן עונת
מבחן אחת אינה מגבלה — אנחנו לא מכריעים בין אלטרנטיבות, אנחנו
ממפים התנהגות.

--------------------------------------------------------------------
הציר
--------------------------------------------------------------------
מודל העלות הוא  cost(i) ∝ exp(β₁ · PIR_קודם).

`β₁` הוא **תלילות המחיר באיכות** — כמה יקר יותר עולה שחקן טוב
יותר. הערך שנאמד מהדאטה הוא **0.252**.

    β₁ קטן  ->  מחירים שטוחים, כוכב זול יחסית לעומק
    β₁ גדול ->  מחירים תלולים, כוכב יקר מאוד

--------------------------------------------------------------------
נרמול — בלעדיו הסווייפ חסר משמעות
--------------------------------------------------------------------
שינוי β₁ משנה גם את **רמת** המחירים ולא רק את הצורה. בלי תיקון,
הסווייפ יערבב "המחירים תלולים יותר" עם "הכל יקר יותר", ואי אפשר
יהיה לדעת מה גרם למה.

לכן אחרי כל שינוי ב-β₁ העלויות **מנורמלות מחדש** כך שסך העלות של
המאגר נשאר קבוע. הציר מודד **צורה בלבד**.

--------------------------------------------------------------------
המדד
--------------------------------------------------------------------
    ריכוזיות = עלות השחקן היקר בסגל / סך עלות הסגל

זו **בדיוק** ההגדרה שנמדדה במציאות על 9 מועדונים (יום 8):

    פנרבחצ'ה 14.0% .. הפועל ת"א 28.1%   ·   חציון 17.3%

--------------------------------------------------------------------
תחזיות — ננעלו לפני ההרצה
--------------------------------------------------------------------
"""

