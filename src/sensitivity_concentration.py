import io
import contextlib
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import statsmodels.api as sm

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parent))
import roster_optimizer as ro
import optimizer_backtest as ob
import club_rosters as cr
from roster_membership_audit import score_rows
from optimise_consistent import optimise_v2
from final_day7 import prep, MIN_LEGAL_ROSTER

SEP = "=" * 78
BETAS = [0.00, 0.05, 0.10, 0.15, 0.20, 0.252, 0.30, 0.40, 0.50, 0.70, 1.00]
OBSERVED = dict(lo=0.140, hi=0.281, med=0.173)


def h(t):
    print("\n" + SEP + f"\n{t}\n" + SEP)


def recost(cand, beta):
    """עלויות תחת β₁ חלופי, מנורמלות לסך עלות זהה.

    הצורה משתנה; הרמה לא. זה מה שהופך את הציר לציר של **מבנה**.
    """
    pir = cand.pir_lag_shrunk.values.astype(float)
    raw = np.exp(beta * (pir - pir.mean()))
    return raw / raw.sum() * cand.cost.sum()


def main():
    print(SEP)
    print("מחקר הרגישות — ריכוזיות ההקצאה מול תלילות מבנה העלות")
    print("תחזיות ננעלו לפני ההרצה. ראו ראש הקובץ.")
    print(SEP)

    feat, anch, pos, ps = ob.load_all()
    for club, train_max, test in [("TEL", 2023, 2024), ("HTA", 2024, 2025)]:
        cand = prep(club, train_max, test, feat, anch, pos, ps).copy()
        r = cr.roster_df(club, test)
        B = float(r.salary.dropna().sum()) + cr.budget_only_total(club, test)
        pir = cand.pir_lag_shrunk
        h(f"{club} {test}   תקציב {B:,.0f}   מאגר {len(cand)}   "
          f"PIR {pir.min():.1f}-{pir.max():.1f}")
        print(f"  {'β₁':>6}{'PIR*':>8}{'n':>4}{'ריכוזיות':>11}"
              f"{'top2':>8}{'היקר בסגל':>13}{'ניקוד אמת':>11}   מול הנצפה")
        rows = []
        for b in BETAS:
            c2 = cand.copy()
            c2["cost"] = recost(cand, b)
            sel, _ = optimise_v2(c2, B, MIN_LEGAL_ROSTER)
            if sel is None:
                print(f"  {b:>6.3f}   אין פתרון")
                continue
            rr = c2[sel]
            tot = rr.cost.sum()
            conc = float(rr.cost.max() / tot)
            top2 = float(rr.cost.nlargest(2).sum() / tot)
            qt, _, _ = score_rows(rr, "ppm_true", "avail_true", 0.127)
            pstar = (1 / b) if b > 0 else np.inf
            mark = ("✅ בטווח" if OBSERVED["lo"] <= conc <= OBSERVED["hi"]
                    else "מחוץ")
            fit = "  <-- הנאמד" if abs(b - 0.252) < 1e-9 else ""
            print(f"  {b:>6.3f}{pstar:>8.1f}{len(rr):>4}{conc:>10.1%}"
                  f"{top2:>8.1%}{rr.cost.max():>13,.0f}{qt:>11.1f}   "
                  f"{mark}{fit}")
            rows.append((b, conc, qt))
        a = np.array(rows)
        if len(a) > 2:
            i = int(np.argmax(a[:, 1]))
            print(f"\n  שיא הריכוזיות: β₁={a[i,0]:.3f} -> {a[i,1]:.1%}")
            rising = a[i, 0] > a[0, 0] and a[i, 1] > a[0, 1] + 0.01
            falling = a[i, 0] < a[-1, 0] and a[i, 1] > a[-1, 1] + 0.01
            print(f"  עולה לפני השיא: {rising} | יורדת אחריו: {falling}")
            print("  -> " + ("**U הפוך — שתי התחזיות מתאשרות**"
                             if rising and falling else
                             "לא U הפוך. שתי התחזיות נופלות."))

    h("קריאה")
    print(f"  הנצפה במציאות (9 מועדונים, 2025/26): "
          f"{OBSERVED['lo']:.1%} .. {OBSERVED['hi']:.1%}, "
          f"חציון {OBSERVED['med']:.1%}")
    print("\n  אם β₁ הנאמד (0.252) מייצר ריכוזיות בתוך הטווח הנצפה —")
    print("  המנוע משחזר התנהגות אמיתית של מועדונים, וזו התוצאה")
    print("  החזקה ביותר שהפרויקט יכול לייצר בלי עוד עונות מבחן.")
    print(SEP)


if __name__ == "__main__":
    main()
